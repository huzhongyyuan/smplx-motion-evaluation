"""Read caption-specific external model outputs through original T2M datasets."""
from collections import defaultdict
import json
from pathlib import Path
import numpy as np
import torch
from contracts import require
from source_lock import sha

def padded_tokens(text, max_text_len=20):
    raw = text['tokens'][:max_text_len]
    tokens = ['sos/OTHER']+raw+['eos/OTHER']
    cap_len = len(tokens)
    return tokens+['unk/OTHER']*(max_text_len+2-cap_len), cap_len

def expected_entry_count(rows, text_dir):
    count = 0
    for row in rows:
        native = np.load(row['native_path'], allow_pickle=False)
        require(native.ndim == 2 and native.shape[1] == 263 and 40 <= len(native) < 200 and np.isfinite(native).all(), 'Invalid original HML source')
        has_full = False
        for line in (Path(text_dir)/(row['source_id']+'.txt')).read_text().splitlines():
            fields = line.split('#'); require(len(fields) >= 4, 'Malformed official HML caption')
            start, end = float(fields[2]), float(fields[3])
            start = 0 if np.isnan(start) else start; end = 0 if np.isnan(end) else end
            if start == 0 and end == 0: has_full = True
            else: count += int(40 <= len(native[int(start*20):int(end*20)]) < 200)
        count += int(has_full)
    return count

def condition_groups(path, plan_path, rep, native_ds):
    """Validate the frozen condition identity and order before reading outputs."""
    plan_sha = sha(plan_path)
    with Path(plan_path).open() as f:
        plans = [r for line in f if (r := json.loads(line))['replication'] == rep]
    require(plans, f'Missing condition-plan replication{rep}')
    plans.sort(key=lambda r: r['order_index'])
    require([r['order_index'] for r in plans] == list(range(len(native_ds))), 'Condition order must be a complete permutation')
    require({r['entry_name'] for r in plans} == set(native_ds.name_list), 'Condition-plan official entry coverage differs')
    with Path(path).open() as f:
        records = [r for line in f if (r := json.loads(line))['replication'] == rep]
    require(records, f'Missing generation replication{rep}')
    entries = defaultdict(list)
    for r in records: entries[r['entry_name']].append(r)
    require(set(entries) == set(native_ds.name_list), 'Generated caption-entry coverage differs from original evaluator dataset')
    groups = []
    for plan in plans:
        name = plan['entry_name']
        samples = sorted(entries[name], key=lambda r: r['repeat_index'])
        require(plan['repeats'] in (1, 30), 'Invalid frozen multimodal repeat count')
        require([r['repeat_index'] for r in samples] == list(range(plan['repeats'])), 'Generation repeats differ from frozen plan')
        text_options = native_ds.data_dict[name]['text']
        # Identical duplicate captions in official files are legitimate.
        require(any(x['caption'] == plan['caption'] and padded_tokens(x) == (plan['tokens'], plan['cap_len'])
                    for x in text_options), 'Frozen caption/tokens are not an official condition for this entry')
        for r in samples:
            for key in ('order_index', 'caption', 'tokens', 'cap_len', 'length20', 'length_policy'):
                require(r[key] == plan[key], f'Generated {key} differs from frozen condition plan')
            require(r['condition_plan_sha256'] == plan_sha, 'Condition-plan bytes changed')
            require(r['generation_seed'] == plan['generation_seed_base']+r['repeat_index'], 'Generation seed differs from frozen plan')
            checkpoint = r['model_checkpoint_sha256']
            require(len(checkpoint) == 64 and all(c in '0123456789abcdef' for c in checkpoint), 'Invalid checkpoint SHA256')
        groups.append((plan, samples))
    require(sum(p['repeats'] == 30 for p in plans) == 100, 'Official Multimodality requires100 frozen conditions')
    require(len({r['model_checkpoint_sha256'] for r in records}) == 1, 'Mixed model checkpoints in one replication')
    return groups, len(records)

def loaders_for_rep(path, plan_path, rep, native_ds, opt, vectorizer, mean, std):
    from motion_loaders.comp_v6_model_dataset import CompV6GeneratedDataset
    from motion_loaders.model_motion_loaders import MMGeneratedDataset, collate_fn
    groups, count = condition_groups(path, plan_path, rep, native_ds)
    generated, multimodal = [], []
    for plan, samples in groups:
        motions = []
        for r in samples:
            require(sha(r['motion263_path']) == r['motion263_sha256'], 'Generated bytes changed')
            x = np.load(r['motion263_path'], allow_pickle=False)
            require(x.ndim == 2 and x.shape == (r['length20'], 263) and np.isfinite(x).all(), 'Invalid generated263D motion')
            # Original "double" cropping can yield36 frames from a legal40-frame source.
            require(36 <= len(x) <= 196 and len(x) % 4 == 0, 'Generated duration must meet frozen T2M unit4 length protocol')
            motions.append(dict(motion=(x-mean)/std, length=len(x)))
        generated.append(dict(motions[0], caption=plan['caption'], tokens=plan['tokens'], cap_len=plan['cap_len']))
        if len(motions) == 30:
            multimodal.append(dict(caption=plan['caption'], tokens=plan['tokens'], cap_len=plan['cap_len'], mm_motions=motions))
    require(len(multimodal) == 100, 'Official Multimodality requires100 conditions with30 repeats')
    # Bypass only the original class's model-specific generation constructor.
    # Its sample formatting, padding, vectorizer and MM sorting run unchanged.
    dataset = CompV6GeneratedDataset.__new__(CompV6GeneratedDataset)
    dataset.opt = opt; dataset.w_vectorizer = vectorizer
    dataset.generated_motion = generated; dataset.mm_generated_motion = multimodal
    mm = MMGeneratedDataset(opt, dataset, vectorizer)
    return (torch.utils.data.DataLoader(dataset, batch_size=32, num_workers=0, shuffle=False, drop_last=True, collate_fn=collate_fn),
            torch.utils.data.DataLoader(mm, batch_size=1, num_workers=0)), count
